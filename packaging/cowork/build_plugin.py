"""Build the Prismor plugin for Claude Cowork (a .plugin zip) on any host.

    python packaging/cowork/build_plugin.py dist/prismor-X.whl out/ [--arch x86_64|aarch64] [--agent-key-file F]

Cowork runs plugin hooks inside a Linux sandbox (Python 3.13, egress limited to
the account's allowed domains), so the plugin carries the runtime and its
dependencies for that platform under vendor/. Without --agent-key-file the
result is the template the console fills in: it adds agent.key per download.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
# The vendored runtime only needs the core package; framework adapters and the
# wheel's console scripts are dead weight in the sandbox.
TRIM = ("bin", "immunity-agent.pth")


def cowork_policy() -> str:
    """dev-safe, plus the two calls Cowork needs: secret-file reads block (the
    agent works on the user's own files), and egress only reports, since the
    sandbox already has its own allowlist and web research is core work."""
    sys.path.insert(0, str(REPO))
    from prismor.runtime import modes

    policy = yaml.safe_load(modes.compile_mode(modes.get_mode("dev-safe")))
    policy["settings"]["mode_id"] = "dev-safe+cowork"
    policy["settings"]["egress"]["mode"] = "observe"
    rules = [r for r in policy.get("rules") or [] if r.get("id") != "secret-file-shell-read"]
    policy["rules"] = [{"id": "secret-file-shell-read", "mode": "enforce"}, *rules]
    return "# Prismor policy for Claude Cowork (dev-safe + cowork overlay), generated by build_plugin.py\n" + yaml.safe_dump(policy, sort_keys=False)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("wheel", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--arch", choices=("x86_64", "aarch64"), default="x86_64")
    ap.add_argument("--python", default="3.13", help="the sandbox's Python (default: 3.13)")
    ap.add_argument("--agent-key-file", type=Path)
    a = ap.parse_args()
    ver = a.wheel.name.split("-")[1]

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp) / "plugin"
        shutil.copytree(HERE / "template", root)
        manifest = root / ".claude-plugin" / "plugin.json"
        manifest.write_text(manifest.read_text().replace("__VERSION__", ver))
        (root / "policy.yaml").write_text(cowork_policy())
        subprocess.run([
            sys.executable, "-m", "pip", "install", "--quiet", "--target", str(root / "vendor"),
            "--platform", f"manylinux2014_{a.arch}", "--python-version", a.python,
            "--implementation", "cp", "--only-binary=:all:", str(a.wheel),
        ], check=True)
        vendor = root / "vendor"
        for p in [*vendor.glob("prismor_*"), *(vendor / t for t in TRIM)]:
            shutil.rmtree(p) if p.is_dir() else p.unlink(missing_ok=True)
        if a.agent_key_file:
            (root / "agent.key").write_text(a.agent_key_file.read_text().strip())

        a.out.mkdir(parents=True, exist_ok=True)
        dest = a.out / f"prismor-cowork-linux-{a.arch}.plugin"
        # No archive comment and no zip64: the console appends agent.key by
        # rewriting only the central directory (lib/zip-append.ts).
        with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(root.rglob("*")):
                if f.is_file() and "__pycache__" not in f.parts:
                    info = zipfile.ZipInfo.from_file(f, f.relative_to(root).as_posix())
                    info.compress_type = zipfile.ZIP_DEFLATED
                    z.writestr(info, f.read_bytes())
    print(dest)


if __name__ == "__main__":
    main()
