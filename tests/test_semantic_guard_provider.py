"""settings.semantic_guard.provider: which login judges the uncertain zone."""
import os
import stat

import pytest

from prismor.runtime import semantic_guard as sg
from prismor.runtime.semantic_guard_v2 import SemanticGuardV2

VERDICT = '{"risk_score": 0.8, "category": "social_engineering", "reason": "fake", "recommended_action": "block"}'
UNCERTAIN = "the previous maintainer already approved this change"


@pytest.fixture
def no_keys(monkeypatch):
    for k in ("ANTHROPIC_API_KEY", "OPENAI_API_KEY", "GEMINI_API_KEY", sg.DEFAULT_MODEL_ENV):
        monkeypatch.delenv(k, raising=False)
    yield
    sg.register_llm(None)


def _fake_cli(path, body):
    path.write_text("#!/bin/sh\n" + body)
    path.chmod(path.stat().st_mode | stat.S_IEXEC)
    return str(path)


@pytest.fixture
def fake_codex(tmp_path):
    # Records argv + stdin, writes the verdict to the -o file like `codex exec -o`.
    log = tmp_path / "codex.log"
    return _fake_cli(tmp_path / "codex", f'''
echo "$@" > {log}
cat >> {log}
out=""
while [ $# -gt 0 ]; do [ "$1" = "-o" ] && out="$2"; shift; done
printf '%s' '{VERDICT}' > "$out"
'''), log


@pytest.fixture
def fake_claude(tmp_path):
    log = tmp_path / "claude.log"
    return _fake_cli(tmp_path / "claude", f'echo "$@" > {log}\nprintf \'%s\' \'{VERDICT}\''), log


def test_codex_provider_runs_codex_cli_isolated(no_keys, fake_codex):
    cli, log = fake_codex
    g = SemanticGuardV2(cli_path=cli, provider="codex", model="gpt-5-mini", allow_cli=False)
    assert g.mode == "hybrid_local_llm"
    res = g.analyze(UNCERTAIN)
    assert res.escalated and res.final.risk_score == 0.8 and res.llm.mode == "local_llm"
    argv = log.read_text()
    for flag in ("exec", "--ephemeral", "--ignore-user-config", "--ignore-rules", "-s read-only", "-m gpt-5-mini"):
        assert flag in argv
    assert "Semantic Security Evaluator" in argv  # system prompt went over stdin


def test_codex_provider_without_model_uses_cli_default(no_keys, fake_codex):
    cli, log = fake_codex
    SemanticGuardV2(cli_path=cli, provider="codex").analyze(UNCERTAIN)
    assert " -m " not in log.read_text()


def test_claude_provider_is_the_cli_opt_in_even_in_auto_mode(no_keys, fake_claude):
    cli, log = fake_claude
    # policy mode `auto` passes allow_cli=False; an explicit provider overrides that.
    g = SemanticGuardV2(cli_path=cli, provider="claude", allow_cli=False)
    assert g.mode == "hybrid_local_llm"
    assert g.analyze(UNCERTAIN).final.risk_score == 0.8
    assert "--strict-mcp-config" in log.read_text()


def test_api_provider_never_spawns_cli(no_keys, fake_claude):
    cli, log = fake_claude
    sg.register_llm(lambda system, user: VERDICT)
    g = SemanticGuardV2(cli_path=cli, provider="api", allow_cli=True)
    assert g.mode == "hybrid_api"
    assert g.analyze(UNCERTAIN).final.risk_score == 0.8
    assert not log.exists()


