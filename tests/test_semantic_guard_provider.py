def test_project_policy_provider_deep_merges_into_default_stanza(tmp_path):
    from prismor.runtime.policy_engine import PolicyEngine
    (tmp_path / ".prismor").mkdir()
    (tmp_path / ".prismor" / "policy.yaml").write_text(
        'version: "1.0"\nsettings:\n  semantic_guard:\n    provider: codex\n    model: ""\n'
    )
    cfg = PolicyEngine(workspace=tmp_path).semantic_guard_config
    assert cfg["provider"] == "codex"
    assert cfg["enabled"] is True and "low_threshold" in cfg  # defaults survived


def test_setup_writes_judge_under_existing_settings(tmp_path):
    from prismor.runtime.setup_wizard import _render_selection_policy, _write_judge_setting
    import yaml
    (tmp_path / ".prismor").mkdir()
    pol = tmp_path / ".prismor" / "policy.yaml"
    pol.write_text(_render_selection_policy(["destructive-command"]))
    _write_judge_setting(tmp_path, "claude", "claude-haiku-4-5-20251001")
    txt = pol.read_text()
    assert txt.startswith("# Generated by `prismor setup`")  # comments kept
    raw = yaml.safe_load(txt)
    assert raw["settings"]["selection"] == "explicit"
    assert raw["settings"]["semantic_guard"] == {"provider": "claude", "model": "claude-haiku-4-5-20251001"}
    assert raw["rules"] == [{"id": "destructive-command", "mode": "enforce"}]
    # second run merges instead of duplicating the key
    _write_judge_setting(tmp_path, "codex", "")
    raw = yaml.safe_load(pol.read_text())
    assert raw["settings"]["semantic_guard"]["provider"] == "codex"
    assert raw["rules"] == [{"id": "destructive-command", "mode": "enforce"}]


